// Функция проверки валидности изображения
function isValidImage(deck) {
  if (!deck || !deck.img) return false;

  if (deck.img === '#' || deck.img === '' || deck.img === 'decksImg/' || deck.img.includes('decksImg/') && deck.img === 'decksImg/deck1Arena2.jpg') {
    return false;
  }
  
  if (deck.img.startsWith('decksImg/')) {
    return false;
  }
  
  return true;
}

function isValidImage(deck) {
  return deck && deck.img && deck.img !== '#' && deck.img !== '' && !deck.img.startsWith('decksImg/');
}

function showDeck(slot, deck) {
  if (!slot) return;
  const img = slot.querySelector('img');
  const elixirSpan = slot.querySelector('.meta_elixir');
  
  if (!deck || !isValidImage(deck)) {
    slot.style.display = 'none';
    return;
  }
  
  slot.style.display = 'block';
  if (img) img.src = deck.img;
  if (elixirSpan) elixirSpan.textContent = `Сред. стоимость: ${deck.elixir}`;
}

function render() {
  const key = arenaKeys[currentArenaIndex];
  const list = decks[key];

  if (!list) return;

  // 1 и 2 колода фиксированные
  showDeck(slot1, list[0]);
  showDeck(slot2, list[1]);

  // 3 колода
if (list.length > 2) {
  showDeck(slot3, list[currentThirdIndex]);
  deck3Wrap.style.display = 'flex';
} else {
  deck3Wrap.style.display = 'none';
  showDeck(slot3, null);
}

  if (select) select.value = key;
}

function switchArena(delta) {
  currentArenaIndex += delta;

  if (currentArenaIndex < 0) currentArenaIndex = 0;
  if (currentArenaIndex >= arenaKeys.length) currentArenaIndex = arenaKeys.length - 1;

  currentThirdIndex = 2;
  render();
}

function switchDeck3(delta) {
  const key = arenaKeys[currentArenaIndex];
  const list = decks[key];

  if (!list || list.length <= 2) return;

  let attempts = 0;
  const maxAttempts = list.length;
  
  do {
    currentThirdIndex += delta;
    
    if (currentThirdIndex < 2) {
      currentThirdIndex = list.length - 1;
    }
    
    if (currentThirdIndex >= list.length) {
      currentThirdIndex = 2;
    }
    
    attempts++;
 
    if (attempts >= maxAttempts) {
      if (slot3) slot3.style.display = 'none';
      if (deck3Wrap) deck3Wrap.style.display = 'none';
      return;
    }
    
  } while (!isValidImage(list[currentThirdIndex]));

  render();
}
if (select) {
  select.addEventListener('change', (e) => {
    const index = arenaKeys.indexOf(e.target.value);
    if (index !== -1) {
      currentArenaIndex = index;
      currentThirdIndex = 2;
      render();
    }
  });
}

